const isLocale = (value: string): value is Locale => AVAILABLE_LOCALES.includes(value as Locale);

const detectLocale = (): Locale => {
    if (typeof window === 'undefined') {
        return 'es';
    }

    const stored = window.localStorage.getItem(STORAGE_KEY) ?? window.localStorage.getItem(LEGACY_STORAGE_KEY);
    if (stored && isLocale(stored)) {
        return stored;
    }

    const browserLang = window.navigator.language.toLowerCase();
    const exactMatch = AVAILABLE_LOCALES.find((locale) => browserLang.startsWith(locale));
    return exactMatch ?? 'es';
};

const getByPath = (source: TranslationNode, path: string): string | undefined => {
    const keys = path.split('.');
    let current: TranslationNode | undefined = source;

    for (const key of keys) {
        if (!current || typeof current === 'string' || !(key in current)) {
            return undefined;
        }
        current = current[key];
    }

    return typeof current === 'string' ? current : undefined;
};

const interpolate = (template: string, params?: Record<string, string | number>): string => {
    if (!params) {
        return template;
    }

    return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
        const value = params[key];
        return value === undefined ? '' : String(value);
    });
};

interface I18nContextValue {
    locale: Locale;
    setLocale: (locale: Locale) => void;
    t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider = ({ children }: { children: ReactNode }) => {
    const [locale, setLocale] = useState<Locale>(detectLocale);

    useEffect(() => {
        if (typeof window !== 'undefined') {
            window.localStorage.setItem(STORAGE_KEY, locale);
        }
    }, [locale]);

    const t = useCallback((key: string, params?: Record<string, string | number>) => {
        const template = getByPath(translations[locale], key) ?? getByPath(translations.en, key) ?? getByPath(translations.es, key) ?? key;
        return interpolate(template, params);
    }, [locale]);

    const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);

    return (
        <I18nContext.Provider value={value}>
            {children}
        </I18nContext.Provider>
    );
};

// eslint-disable-next-line react-refresh/only-export-components
export const useI18n = () => {
    const context = useContext(I18nContext);
    if (!context) {
        throw new Error('useI18n must be used within I18nProvider');
    }
    return context;
};
